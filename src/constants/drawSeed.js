// Shared showcase seed for Labs Draw demos.
// "weekend web labs" in green rounded strokes, a cream flask with amber
// bubbles, and an amber underline under "labs". Coordinates stay in the
// source SVG viewBox (0 0 1060 200). Cubics are sampled into line polylines;
// the flask liquid is a closed fill; the two bubbles are ellipses.
// Used by Draw.vue and CbunPreviewDraw.vue.

/** Target inset as a fraction of the shorter canvas edge (~50% artwork fill). */
export const DRAW_DEMO_FIT_INSET = 0.25;

/**
 * Camera scale applied after the inset fit. 0.85 is about 15% smaller than
 * the fitted first paint, with the same artwork still centered.
 */
export const DRAW_DEMO_FIT_SCALE = 0.85;

export function fitDrawDemoView(instance) {
  if (!instance?.fitView) return;
  const rect = instance.canvasEl?.getBoundingClientRect?.();
  const pad =
    rect?.width && rect?.height
      ? Math.round(Math.min(rect.width, rect.height) * DRAW_DEMO_FIT_INSET)
      : 96;
  instance.fitView(pad);
  if (!rect?.width || !rect?.height || typeof instance.scaleAround !== 'function') return;
  instance.scaleAround(DRAW_DEMO_FIT_SCALE, rect.width / 2, rect.height / 2);
  const vp = instance.toJSON?.().viewport;
  if (vp && typeof instance.setViewport === 'function') {
    instance.setViewport({ x: vp.x, y: vp.y, scale: vp.scale });
  } else {
    instance.render?.({ scene: false });
  }
}

